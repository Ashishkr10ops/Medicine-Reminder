
#ifndef ALERT_H
#define ALERT_H

#include <string>

// Stores the medicine ID and message associated with an alert.
struct Alert
{
    int medicineId;
    std::string message;
};

// Node of the singly linked list used to store alerts.
struct AlertNode
{
    Alert alert;     // Alert information stored in this node.
    AlertNode *next; // Pointer to the next alert node.
};

// Manages dynamically allocated alert nodes using a linked list.
class AlertManager
{
private:
    AlertNode *head; // Points to the first node; nullptr means the list is empty.

public:
    // Initializes the alert list as empty.
    AlertManager();

    // Frees all remaining nodes when the manager is destroyed.
    ~AlertManager();

    // Appends an alert to the end of the linked list.
    void addAlert(const Alert &alert);

    // Removes all alerts and releases their dynamically allocated memory.
    void clearAlerts();

    // Traverses the list and displays every stored alert.
    void displayAlerts();
};

// Checks inventory records and generates low-stock and expiry alerts.
void checkAlerts();

// Displays the alerts generated by checkAlerts().
void displayAlerts();

#endif
